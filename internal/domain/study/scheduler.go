package study

import "time"

// Scheduler назначает следующий показ карточки.
//
// Это чистая функция, оформленная интерфейсом: (состояние, оценка, момент) →
// новое состояние. Ни базы, ни обращений к time.Now, ни скрытой случайности —
// поэтому реализация проверяется табличными тестами, а любая цепочка
// повторений воспроизводима.
//
// Аргумент now — момент ответа, а не «сейчас»: сценарий передаёт время,
// зафиксированное на входе, и повторная обработка того же ответа даёт тот же
// результат. Реализация SM-2 появится в T-009.
type Scheduler interface {
	Next(cur CardState, r Rating, now time.Time) CardState
}
