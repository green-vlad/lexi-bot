ALTER TABLE daily_counters
    ADD COLUMN new_limit INTEGER NOT NULL DEFAULT 0 CHECK (new_limit >= 0);

COMMENT ON COLUMN daily_counters.new_limit IS
    'Норма новых слов, зафиксированная на эти сутки; 0 — не зафиксирована';

