// Package study описывает интервальное повторение: состояние карточки, оценку
// ответа, запись в журнале повторений и интерфейс планировщика.
//
// Сам алгоритм (SM-2) появляется здесь же отдельной реализацией Scheduler.
// Разделение неслучайно: типы описывают, из чего состоит обучение, а Scheduler —
// правило, по которому оно движется, и это правило заменяемо. Когда захочется
// FSRS, он станет второй реализацией одного интерфейса, а хранилище, сценарии
// и Telegram-слой останутся нетронутыми.
//
// Пакет не обращается ко времени сам: момент всегда приходит аргументом, и
// поэтому любую цепочку повторений можно проиграть в тесте за микросекунды.
package study

