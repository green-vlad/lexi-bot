// Package port объявляет интерфейсы, через которые сценарии добираются
// до внешнего мира: до базы, до часов, до источника случайности.
//
// Интерфейсы живут на стороне потребителя — это и есть правило зависимостей
// из плана (§3). Сценарий описывает, что ему нужно от хранилища, а адаптер
// в internal/adapter/storage/postgres подстраивается под это описание,
// а не наоборот. Поэтому здесь нет ни одного типа из pgx, а тесты сценариев
// обходятся фейками на пару десятков строк.
//
// Порты растут вместе со сценариями: здесь объявлено то, что нужно вехам
// M2–M5, и каждая следующая задача добавляет ровно те методы, которые ей
// понадобились. Заранее придуманный метод — это метод, который никто
// не позовёт и который никак не проверить.
package port

import (
	"context"
	"errors"
	"time"
)

// Ошибки хранилища, которые для сценария означают не аварию, а ответ.
// Репозиторий оборачивает их описанием операции, а сценарий узнаёт через
// errors.Is и решает, что делать дальше.
var (
	// ErrNotFound — строки нет. Сценарий сам решает, создать запись,
	// показать «ничего не найдено» или вернуть ошибку выше.
	ErrNotFound = errors.New("запись не найдена")
	// ErrConflict — запись нарушает уникальность: слово уже есть в словаре,
	// курс уже заведён.
	ErrConflict = errors.New("запись конфликтует с существующей")
	// ErrInvalidData — данные не прошли проверку на стороне базы. Обычно это
	// означает ошибку в коде: домен обязан был отсечь такое раньше.
	ErrInvalidData = errors.New("данные не проходят проверку хранилища")
)

// Clock — источник текущего времени.
//
// Время приходит интерфейсом, потому что почти вся логика обучения завязана
// на моменты: срок показа карточки, граница суток, время напоминания.
// С подменёнными часами тест проигрывает месяц занятий за миллисекунды.
type Clock interface {
	Now() time.Time
}

// ClockFunc превращает обычную функцию в Clock.
type ClockFunc func() time.Time

// Now вызывает саму функцию.
func (f ClockFunc) Now() time.Time { return f() }

// Rand — источник случайности.
//
// Нужен в двух местах: джиттер интервалов в планировщике и подбор
// дистракторов для режима выбора. Оба должны быть воспроизводимы в тестах,
// поэтому math/rand в прикладном коде не появляется.
//
// Интерфейс шире, чем study.Rand, и любая его реализация годится и туда.
type Rand interface {
	// Float64 возвращает число в промежутке [0, 1).
	Float64() float64
	// Intn возвращает число в промежутке [0, n).
	Intn(n int) int
	// Shuffle перемешивает n элементов, меняя их местами через swap.
	Shuffle(n int, swap func(i, j int))
}

// TxManager выполняет функцию в транзакции.
//
// Транзакция едет в контексте, а не отдельным аргументом: иначе её тип
// (а с ним и pgx) протёк бы во все сигнатуры репозиториев и в сценарии.
// Репозитории достают транзакцию из контекста сами; вне InTx они работают
// с пулом напрямую.
//
// Вложенный вызов InTx присоединяется к уже открытой транзакции, а не
// открывает вторую: «ввести новые слова» внутри «принять ответ» должно
// откатываться вместе со всем остальным.
//
// Правило простое: если fn вернула ошибку, не изменилось ничего.
type TxManager interface {
	InTx(ctx context.Context, fn func(ctx context.Context) error) error
}
