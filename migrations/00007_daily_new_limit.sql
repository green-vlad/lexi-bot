-- Дневная норма новых слов запоминается на сутки вперёд.
--
-- Без этого изменение нормы действовало бы задним числом. Человек, поднявший
-- её с пяти до двадцати в середине дня, получал бы пятнадцать новых слов
-- сверх запланированного — и через неделю очередь повторений, которую
-- не заказывал. Опустивший с двадцати до пяти после десяти начатых слов
-- слышал бы «на сегодня всё» так, будто нормы и не было.
--
-- Норма фиксируется в момент, когда человек в этот день впервые начинает
-- учить слово, и до конца суток не меняется. Новое значение вступает в силу
-- назавтра — тогда же, когда обнуляется счётчик.
--
-- Ноль означает «норма на этот день не зафиксирована»: так выглядят строки,
-- заведённые до этой миграции, и для них берётся текущая настройка.

