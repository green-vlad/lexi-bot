package port

import "lexi-bot/internal/domain/user"

// Args — именованные подстановки в сообщении.
//
// Именованные, а не позиционные: в переводе слова меняются местами
// («{{.Count}} карточек до {{.Date}}» против «by {{.Date}}, {{.Count}} cards»),
// и порядок аргументов держать одинаковым не выйдет.
type Args map[string]any

// Localizer переводит сообщения на язык одного пользователя.
//
// Ошибка означает, что ключа нет ни в одном каталоге, то есть ошибку
// в коде. Возвращать вместо этого пустую строку нельзя: пустое сообщение
// в чате выглядит как поломка бота и молча уходит к пользователю, а ошибка
// попадает в лог и в тест.
type Localizer interface {
	// T переводит сообщение без числа.
	T(key string, args Args) (string, error)

	// Plural переводит сообщение с числом, выбирая нужную форму:
	// «1 карточка», «2 карточки», «5 карточек». Число доступно в переводе
	// как {{.Count}} и отдельно передавать его в args не нужно.
	Plural(key string, count int, args Args) (string, error)

	// Lang — язык этого локализатора.
	Lang() user.UILang
}

// Catalog выдаёт локализатор для языка интерфейса.
type Catalog interface {
	// For возвращает локализатор языка. Для неподдерживаемого языка
	// возвращается локализатор языка по умолчанию: остаться без ответа
	// хуже, чем получить его не на родном языке.
	For(lang user.UILang) Localizer
}
